"""Import and inspect user-supplied GIFs; does not invoke an ESP-IDF build."""
import argparse
import hashlib
import json
from pathlib import Path
import re
import struct

ROOT = Path(__file__).resolve().parents[1]
BOARD = ROOT / "main/boards/UTA-robot"
DESTINATION = BOARD / "assets/emotions"


def catalog():
    return re.findall(r'UTA_EYE\((\w+), "([^"]+)", "([^"]+)"\)',
                      (BOARD / "uta_emotion_catalog.inc").read_text(encoding="utf-8"))


def inspect_gif(data):
    if len(data) < 14 or data[:6] not in (b"GIF89a", b"GIF87a"):
        raise ValueError("Invalid GIF header")
    width, height, packed, background, _ = struct.unpack_from("<HHBBB", data, 6)
    if (width, height) != (240, 240) or not packed & 128:
        raise ValueError("Requires 240x240 GIF with global color table")
    colors = 1 << ((packed & 7) + 1)
    if background >= colors:
        raise ValueError("Invalid GIF background")
    cursor = 13 + colors * 3
    frames = 0
    delays = []
    delay = 0
    loop = None

    def byte():
        nonlocal cursor
        if cursor >= len(data):
            raise ValueError("Truncated GIF")
        result = data[cursor]
        cursor += 1
        return result

    def blocks():
        nonlocal cursor
        result = bytearray()
        while True:
            size = byte()
            if size == 0:
                return bytes(result)
            if cursor + size > len(data):
                raise ValueError("Truncated GIF block")
            result.extend(data[cursor:cursor + size])
            cursor += size

    while True:
        marker = byte()
        if marker == 0x3b:
            if frames < 2 or cursor != len(data):
                raise ValueError("Requires complete animated GIF")
            return {"width": width, "height": height, "frames": frames,
                    "duration_ms": sum(delays), "min_delay_ms": min(delays),
                    "loop": loop, "bytes": len(data),
                    "sha256": hashlib.sha256(data).hexdigest()}
        if marker == 0x21:
            label = byte()
            if label == 0xf9:
                size = byte()
                if size != 4 or cursor + 5 > len(data):
                    raise ValueError("Invalid GIF graphics control")
                control, delay_cs, _ = struct.unpack_from("<BHB", data, cursor)
                if ((control >> 2) & 7) > 3:
                    raise ValueError("Unsupported GIF disposal")
                delay = max(10, delay_cs * 10)
                cursor += 4
                if byte() != 0:
                    raise ValueError("Invalid graphics control terminator")
            else:
                payload = blocks()
                if label == 0xff and payload.startswith(b"NETSCAPE2.0\x01"):
                    loop = int.from_bytes(payload[12:14], "little")
        elif marker == 0x2c:
            if cursor + 9 > len(data):
                raise ValueError("Truncated GIF frame")
            left, top, frame_width, frame_height, flags = struct.unpack_from("<HHHHB", data, cursor)
            cursor += 9
            if not frame_width or not frame_height or left + frame_width > width or top + frame_height > height:
                raise ValueError("GIF frame outside canvas")
            if flags & 128:
                cursor += 3 * (1 << ((flags & 7) + 1))
            if not 2 <= byte() <= 8 or not blocks():
                raise ValueError("Invalid GIF LZW data")
            frames += 1
            delays.append(delay)
            delay = 0
            if frames > 500:
                raise ValueError("GIF frame budget exceeded")
        else:
            raise ValueError(f"Invalid GIF block: {marker:#x}")


def prepare(source=None):
    records = []
    source = Path(source) if source else DESTINATION
    # Validate the whole collection before replacing any imported files.
    for name, stem, filename in catalog():
        path = source / filename
        data = path.read_bytes()
        if len(data) > 256 * 1024:
            raise ValueError(f"GIF too large: {filename}")
        records.append((name, stem, filename, data, inspect_gif(data)))
    DESTINATION.mkdir(parents=True, exist_ok=True)
    for _, _, filename, data, _ in records:
        if source.resolve() != DESTINATION.resolve():
            (DESTINATION / filename).write_bytes(data)
    manifest = [{"id": name, "file": filename, **metadata}
                for name, _, filename, _, metadata in records]
    (DESTINATION / "manifest.json").write_text(
        json.dumps({"version": 1, "emotions": manifest}, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    lines = ['# Generated by scripts/prepare_uta_emotions.py', 'list(APPEND UTA_EYE_GIFS']
    lines += [f'    "boards/UTA-robot/assets/emotions/{record[2]}"' for record in records]
    lines += [')', '']
    (DESTINATION / "emotions.cmake").write_text("\n".join(lines), encoding="utf-8")
    print(f"Prepared {len(records)} original GIFs ({sum(len(record[3]) for record in records)} bytes).")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--source", type=Path)
    prepare(parser.parse_args().source)
